
const PDFDocument = require("pdfkit");
const Athlete = require("../models/Athlete");
const EligibilityCriteria = require("../models/EligibilityCriteria");
const AthleteEligibility = require("../models/AthleteEligibility");

const downloadEligibilityReport = async (req, res) => {
    try {
        const { athleteId } = req.params;

        const athlete = await Athlete.findById(athleteId).lean();

        if (!athlete) {
            return res.status(404).json({
                success: false,
                message: "Athlete not found"
            });
        }

        const eligibility = await AthleteEligibility.findOne({
            athleteId
        })
            .populate("criteriaId")
            .populate("reviewedBy", "name email")
            .sort({ reviewedAt: -1 })
            .lean();

        if (!eligibility) {
            return res.status(404).json({
                success: false,
                message: "No eligibility review exists for this athlete"
            });
        }

        const criteria = eligibility.criteriaId;

        const safeName = (athlete.name || "athlete")
            .replace(/[^a-z0-9_-]/gi, "_");

        res.setHeader("Content-Type", "application/pdf");
        res.setHeader(
            "Content-Disposition",
            `attachment; filename="${safeName}_eligibility_report.pdf"`
        );

        const doc = new PDFDocument({
            size: "A4",
            margins: { top: 50, bottom: 50, left: 50, right: 50 },
            bufferPages: true
        });

        doc.pipe(res);

        const addField = (label, value) => {
            doc.font("Helvetica-Bold")
                .fontSize(10)
                .fillColor("#334155")
                .text(label);

            doc.font("Helvetica")
                .fontSize(11)
                .fillColor("#0f172a")
                .text(
                    value === null || value === undefined || value === ""
                        ? "Not recorded"
                        : String(value)
                );

            doc.moveDown(0.7);
        };

        doc.fontSize(20)
            .font("Helvetica-Bold")
            .fillColor("#0369a1")
            .text("ATHLETE MANAGEMENT SYSTEM");

        doc.moveDown(0.3);

        doc.fontSize(15)
            .fillColor("#0f172a")
            .text("Athlete Eligibility Report");

        doc.moveDown(1);

        addField("Athlete Name", athlete.name);
        addField("Athlete ID", athlete.externalId || athlete._id);
        addField("Age", athlete.age);
        addField("Position", athlete.position);
        addField("Club", athlete.club);

        doc.moveDown(0.5);
        doc.fontSize(14)
            .font("Helvetica-Bold")
            .text("Eligibility Assessment");

        doc.moveDown(0.6);

        addField("Criteria Name", criteria?.name);
        addField(
            "Required Qualification",
            criteria?.minimumQualificationLevel
        );
        addField(
            "Actual Qualification",
            eligibility.actualQualificationLevel
        );
        addField("Eligibility Status", eligibility.status);
        addField("Evaluation Reason", eligibility.reason);
        addField(
            "Age Eligible",
            eligibility.ageEligible == null
                ? "Not assessed"
                : eligibility.ageEligible ? "Yes" : "No"
        );
        addField(
            "Certificate Verification",
            eligibility.certificatesVerified == null
                ? "Pending"
                : eligibility.certificatesVerified ? "Verified" : "Not verified"
        );
        addField(
            "Documents Complete",
            eligibility.documentsComplete == null
                ? "Pending"
                : eligibility.documentsComplete ? "Yes" : "No"
        );
        addField(
            "Performance Score",
            eligibility.performanceScore == null
                ? "Not assessed"
                : `${eligibility.performanceScore}/100`
        );
        addField("Researcher Remarks", eligibility.researcherRemarks);
        addField(
            "Reviewed By",
            eligibility.reviewedBy?.name || "Not recorded"
        );
        addField(
            "Review Date",
            eligibility.reviewedAt
                ? new Date(eligibility.reviewedAt).toLocaleString("en-IN")
                : "Not recorded"
        );

        doc.moveDown();
        doc.fontSize(8)
            .fillColor("#64748b")
            .text(
                "Generated by the Athlete Management System. This report reflects the saved eligibility record at the time of generation.",
                { align: "left" }
            );

        doc.end();
    } catch (error) {
        console.error("Eligibility PDF error:", error.message);

        if (!res.headersSent) {
            return res.status(500).json({
                success: false,
                message: "Failed to generate eligibility report"
            });
        }

        res.destroy(error);
    }
};


const downloadAllEligibilityReports = async (req, res) => {
    try {
        const Athlete = require("../models/Athlete");
        const AthleteEligibility = require("../models/AthleteEligibility");

        const athletes = await Athlete.find({ isActive: true })
            .sort({ name: 1 })
            .lean();

        const athleteIds = athletes.map((athlete) => athlete._id);

        const reviews = await AthleteEligibility.find({
            athleteId: { $in: athleteIds }
        })
            .populate("criteriaId", "name minimumQualificationLevel")
            .populate("reviewedBy", "name")
            .sort({ reviewedAt: -1, updatedAt: -1 })
            .lean();

        // Keep only the most recent review for each athlete.
        const latestReviews = new Map();

        for (const review of reviews) {
            const id = String(review.athleteId);

            if (!latestReviews.has(id)) {
                latestReviews.set(id, review);
            }
        }

        res.setHeader("Content-Type", "application/pdf");
        res.setHeader(
            "Content-Disposition",
            'attachment; filename="AMS_All_Athletes_Eligibility_Report.pdf"'
        );

        const doc = new (require("pdfkit"))({
            size: "A4",
            layout: "landscape",
            margins: { top: 40, bottom: 40, left: 35, right: 35 }
        });

        doc.pipe(res);

        doc.fontSize(19)
            .fillColor("#0369a1")
            .font("Helvetica-Bold")
            .text("ATHLETE MANAGEMENT SYSTEM");

        doc.moveDown(0.3);
        doc.fontSize(14)
            .fillColor("#0f172a")
            .text("Consolidated Athlete Eligibility Report");

        doc.moveDown(0.3);
        doc.fontSize(9)
            .fillColor("#64748b")
            .text(`Generated: ${new Date().toLocaleString("en-IN")}`);

        doc.moveDown();

        const columns = [
            { label: "Athlete", x: 35, width: 115 },
            { label: "Position", x: 150, width: 75 },
            { label: "Qualification", x: 225, width: 100 },
            { label: "Status", x: 325, width: 105 },
            { label: "Performance", x: 430, width: 75 },
            { label: "Evaluation Reason", x: 505, width: 180 }
        ];

        const drawHeader = () => {
            const y = doc.y;

            doc.rect(35, y, 650, 24).fill("#e0f2fe");

            doc.fillColor("#0f172a")
                .font("Helvetica-Bold")
                .fontSize(9);

            for (const column of columns) {
                doc.text(column.label, column.x + 4, y + 7, {
                    width: column.width - 8,
                    lineBreak: false
                });
            }

            doc.y = y + 30;
            doc.font("Helvetica").fontSize(8);
        };

        drawHeader();

        for (const athlete of athletes) {
            const review = latestReviews.get(String(athlete._id));

            const row = [
                athlete.name || "Unnamed",
                athlete.position || "Not recorded",
                review?.actualQualificationLevel || "Not recorded",
                review?.status || "INSUFFICIENT_DATA",
                review?.performanceScore == null
                    ? "Not assessed"
                    : `${review.performanceScore}/100`,
                review?.reason || "No evaluation recorded"
            ];

            const y = doc.y;
            const rowHeight = 34;

            if (y + rowHeight > doc.page.height - 45) {
                doc.addPage();
                drawHeader();
            }

            const rowY = doc.y;

            doc.fillColor("#0f172a").font("Helvetica").fontSize(8);

            row.forEach((value, index) => {
                const column = columns[index];

                doc.text(String(value), column.x + 4, rowY, {
                    width: column.width - 8,
                    height: rowHeight - 4,
                    ellipsis: true
                });
            });

            doc.y = rowY + rowHeight;
            doc.moveTo(35, doc.y)
                .lineTo(685, doc.y)
                .strokeColor("#e2e8f0")
                .stroke();

            doc.moveDown(0.2);
        }

        doc.moveDown();
        doc.fontSize(9)
            .fillColor("#64748b")
            .text(`Total active athletes: ${athletes.length}`);

        doc.end();
    } catch (error) {
        console.error("Consolidated eligibility PDF error:", error.message);

        if (!res.headersSent) {
            return res.status(500).json({
                success: false,
                message: "Failed to generate consolidated eligibility report"
            });
        }

        res.destroy(error);
    }
};

module.exports = {
    downloadEligibilityReport,
    downloadAllEligibilityReports
};